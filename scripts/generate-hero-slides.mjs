/**
 * Generates src/data/hero-slides.ts by scanning public/images/hero/.
 * Runs automatically before `npm run dev` and `npm run build`,
 * so dropping an image into the folder is all that's needed.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HERO_DIR = join(process.cwd(), "public", "images", "hero");
const OUT_FILE = join(process.cwd(), "src", "data", "hero-slides.ts");
const IMAGE_EXTENSIONS = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png", ".gif"]);

const slides = readdirSync(HERO_DIR)
	.filter((file) => IMAGE_EXTENSIONS.has(file.slice(file.lastIndexOf(".")).toLowerCase()))
	.sort()
	.map((file) => `/images/hero/${file}`);

const content = `/**
 * AUTO-GENERATED by scripts/generate-hero-slides.mjs — do not edit by hand.
 * To add a hero slide, drop an image into public/images/hero/ and restart the dev server.
 */
export const HERO_SLIDES: string[] = ${JSON.stringify(slides, null, "\t")};
`;

writeFileSync(OUT_FILE, content);
console.log(`hero-slides: ${slides.length} image(s) -> ${slides.join(", ") || "(none)"}`);
